//
// Root cause of every mismatch (confirmed by diffing actual drop items, not just counts):
// giran.info's own boss page only lists the top 20 drops by `chance`, so RAID_BOSSES is
// truncated to a 20-item cap wherever a boss's true drop table is longer. RAID_BOSS_DETAILS
// always has the full table. Every one of the 96 mismatches has
// raidBossesDropCount <= 20 and apiDropCount > raidBossesDropCount — never the reverse — and
// for the one checked in detail (Water Spirit Lian, id 25487) RAID_BOSSES's 20 items are
// exactly the API's top 20 by chance, in the same order.
//
// Comparable ids: 146. Of those: 50 match, 96 differ.
// 5 ids exist only in RAID_BOSS_DETAILS (not yet in RAID_BOSSES — see
// ../raid-bosses/missing.ts). 7 ids exist only in RAID_BOSSES (the API lists
// them under a different title: Epic Boss / Queen of Underground / Subclass Raid Boss — see
// ./missing-from-new-source.ts).

