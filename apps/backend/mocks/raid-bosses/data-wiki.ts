// The raid bosses of this server, as the game's own reference states them.
//
// Refreshed by the commands in `scripts/catalogue/`, not edited by hand:
//
//   refresh:drops     one request. Drop tables, item names, icon keys, and the
//                     epic and subclass flags. Writes ./drops.ts and, for the
//                     other game server, ./data-wiki-gamma.ts.
//   refresh:profile   one request per boss. Level, race, all ten statistics,
//                     respawn, soul-crystal level and the skills carried.
//                     Writes this file.
//   refresh:skills    no requests. Builds ./skills.ts from the pages the
//                     profile pass cached.
//
// Three things this file deliberately does not hold. Drops live in ./drops.ts,
// which is four fifths of the data and is refreshed by a different pass. The
// world map and its dungeon plans live in ./world-map.ts. And what a boss
// resists or is vulnerable to lives in ./skills.ts, named here only by key —
// those values belong to a skill and are the same for every boss carrying it.
//
// Locations are never refreshed. The source names them by transliteration of
// another language, so there is no correspondence to follow, and the names here
// were settled by hand.

